package org.appliedtopology.tda4j

import scala.collection.mutable
import scala.util.chaining.*

/** The lower-star filtration of a function on the vertices of a simplicial complex: a simplex enters when its last
  * vertex does, so its value is the largest of its vertices' values. It computes the sublevel-set persistence of the
  * function (a height function on a mesh, a measurement at each node of a network, a scalar field sampled at the
  * vertices of a triangulation).
  *
  * {{{
  * val stream = LowerStar(Seq(Simplex(0, 1, 2), Simplex(2, 3)), v => heights(v))
  * Persistence(stream)
  * }}}
  */
object LowerStar:

  /** The complex generated by `facets` (each facet and all its faces), each simplex valued by the largest `vertexValue`
    * of its vertices. With `superlevel`, valued by the largest of `-vertexValue` instead: the superlevel sets of the
    * function, whose bars are then in negated units (as for a superlevel image).
    */
  def apply(
    facets: Iterable[Simplex[Int]],
    vertexValue: Int => Double,
    superlevel: Boolean = false
  ): ExplicitStream[Int, Double] =
    val sign = if superlevel then -1.0 else 1.0
    val values = mutable.HashMap.empty[Simplex[Int], Double]
    for facet <- facets do
      val vertices = facet.toList
      for size <- 1 to vertices.size; face <- vertices.combinations(size) do
        values.getOrElseUpdate(
          Simplex.from(face),
          face
            .map(v => sign * vertexValue(v))
            .max
            .tap(v => require(!v.isNaN, s"LowerStar: NaN value at a vertex of $face"))
        )
    ExplicitStreamBuilder.fromFilteredFacets(values.toSeq.map((cell, value) => (value, cell)))

  /** The lower-star filtration of the graph on `0 until n` with the given edges: a vertex at its value, an edge at the
    * larger of its ends' values. Vertices that no edge touches are included.
    */
  def ofGraph(
    n: Int,
    edges: Iterable[(Int, Int)],
    vertexValue: Int => Double,
    superlevel: Boolean = false
  ): ExplicitStream[Int, Double] =
    require(n >= 0, s"LowerStar: the number of vertices must be at least 0, got $n")
    val facets = Seq.range(0, n).map(v => Simplex.from(List(v))) ++ edges.map { (a, b) =>
      require(0 <= a && a < n && 0 <= b && b < n && a != b, s"LowerStar: edge ($a, $b) is not an edge on 0 until $n")
      Simplex.from(List(a, b))
    }
    apply(facets, vertexValue, superlevel)
end LowerStar
