package org.appliedtopology.tda4j

import scala.collection.mutable

/** Image, kernel and cokernel of a map of persistence modules that are sums of interval modules, over any field.
  *
  * The source has bars `[b_i, d_i)` and the target `[b'_j, d'_j)`; the map is a matrix with a coefficient for each pair
  * of a source bar `i` and a target bar `j`, given column by column (`columns(i)` maps `j` to the coefficient). A
  * coefficient can be nonzero only where there is a map of interval modules at all, `b'_j <= b_i < d'_j <= d_i`
  * ([[isLegal]]): the generator of bar `i`, born at `b_i`, goes to the component of the target alive then, and the
  * source dies no sooner than the component does.
  *
  * Each result is a list of bars as `(bar index, interval)`; the interval is `[birth, death)` in the numbers of the
  * input. The three are computed by one kind of reduction, with the elder rule:
  *
  *   - the image is the submodule of the target generated by the images of the source generators, each born at its
  *     bar's birth; reducing the generators in order of birth, with the target components ordered by death, a generator
  *     that does not reduce to zero is a bar from its birth to the death of its leading component;
  *   - the cokernel is the target modulo the image; its generators are the target bars, and the relations are the
  *     images of the source generators at their births and each target bar's own death. Taking relations in order of
  *     time, with the generators ordered by birth, a relation that does not reduce to zero kills the youngest generator
  *     in it at its time;
  *   - the kernel is the cokernel of the dual map, in the reversed order of the filtration (a bar `[b, d)` becomes
  *     `[-d, -b)`).
  *
  * The tests check all three against the ranks of the structure maps of the modules, computed by linear algebra.
  */
object MapAlgebra:

  /** A bar as the numbers of its endpoints; `death` may be `Infinity`. */
  final case class Interval(birth: Double, death: Double)

  /** Whether a nonzero coefficient from source bar `s` to target bar `t` is a map of interval modules. */
  def isLegal(s: Interval, t: Interval): Boolean = t.birth <= s.birth && s.birth < t.death && t.death <= s.death

  /** The bars of the image, as (source bar, `[birth of the source bar, death of the leading target component)`). */
  def image[C](
    source: IndexedSeq[Interval],
    target: IndexedSeq[Interval],
    columns: IndexedSeq[Map[Int, C]]
  )(using fr: C is Field): List[(Int, Interval)] =
    val table = mutable.HashMap.empty[Int, mutable.HashMap[Int, C]]
    val bars = mutable.ListBuffer.empty[(Int, Interval)]
    // The component that dies last leads; ties by position.
    val deathOrder = Ordering.by[Int, (Double, Int)](j => (target(j).death, j))
    for i <- source.indices.sortBy(i => (source(i).birth, i)) do
      val birth = source(i).birth
      // The vector lives in the target at `birth`: components dead by then are zero.
      val v = mutable.HashMap.empty[Int, C]
      for (j, c) <- columns(i) if !fr.isEqual(c, fr.zero) && target(j).death > birth do v(j) = c
      var done = false
      while !done do
        if v.isEmpty then done = true
        else
          val lead = v.keysIterator.max(using deathOrder)
          table.get(lead) match
            case Some(u) =>
              val factor = fr.divide(v(lead), u(lead))
              for (j, c) <- u do
                val updated = fr.minus(v.getOrElse(j, fr.zero), fr.times(factor, c))
                if fr.isEqual(updated, fr.zero) then v.remove(j) else v(j) = updated
              v.filterInPlace((j, _) => target(j).death > birth)
            case None =>
              table(lead) = v
              bars += ((i, Interval(birth, target(lead).death)))
              done = true
    bars.toList

  /** The bars of the cokernel, as (target bar, `[its birth, the time its generator is killed)`): one for each target
    * bar that is not killed at its own birth, with the target bar's death if nothing kills it sooner.
    */
  def cokernel[C](
    source: IndexedSeq[Interval],
    target: IndexedSeq[Interval],
    columns: IndexedSeq[Map[Int, C]]
  )(using fr: C is Field): List[(Int, Interval)] =
    // Relations in order of time; at one time, a target bar's death before the image of a source generator born then.
    val events: Seq[(Double, Int, Int)] =
      (target.indices.filter(j => !target(j).death.isInfinite).map(j => (target(j).death, 0, j)) ++
        source.indices.map(i => (source(i).birth, 1, i))).sorted
    val youngest = Ordering.by[Int, (Double, Int)](j => (target(j).birth, j))
    val table = mutable.HashMap.empty[Int, mutable.HashMap[Int, C]]
    val killedAt = mutable.HashMap.empty[Int, Double]
    for (time, kind, index) <- events do
      val r = mutable.HashMap.empty[Int, C]
      if kind == 0 then r(index) = fr.one
      else for (j, c) <- columns(index) if !fr.isEqual(c, fr.zero) do r(j) = c
      var done = false
      while !done do
        if r.isEmpty then done = true
        else
          val lead = r.keysIterator.max(using youngest)
          table.get(lead) match
            case Some(u) =>
              val factor = fr.divide(r(lead), u(lead))
              for (j, c) <- u do
                val updated = fr.minus(r.getOrElse(j, fr.zero), fr.times(factor, c))
                if fr.isEqual(updated, fr.zero) then r.remove(j) else r(j) = updated
            case None =>
              table(lead) = r
              killedAt(lead) = time
              done = true
    target.indices.toList.flatMap { j =>
      val death = killedAt.getOrElse(j, target(j).death)
      Option.when(death > target(j).birth)((j, Interval(target(j).birth, death)))
    }

  /** The bars of the kernel, as (source bar, interval): the cokernel of the transposed map between the reflected
    * modules, reflected back.
    */
  def kernel[C](
    source: IndexedSeq[Interval],
    target: IndexedSeq[Interval],
    columns: IndexedSeq[Map[Int, C]]
  )(using fr: C is Field): List[(Int, Interval)] =
    // `0.0 - x`, not `-x`: no negative zero, which an ordering of doubles would put before 0.0.
    val reflectedSource = target.map(t => Interval(0.0 - t.death, 0.0 - t.birth))
    val reflectedTarget = source.map(s => Interval(0.0 - s.death, 0.0 - s.birth))
    val transposed: IndexedSeq[Map[Int, C]] =
      target.indices.map(j => columns.indices.collect { case i if columns(i).contains(j) => i -> columns(i)(j) }.toMap)
    cokernel(reflectedSource, reflectedTarget, transposed).map((i, reflected) =>
      (i, Interval(0.0 - reflected.death, 0.0 - reflected.birth))
    )
end MapAlgebra
