#!/usr/bin/env python3
"""Turn the benchmark harness's output into papers/common/results.tex.

    python3 papers/tools/bench-to-tex.py RESULTS_DIR [RESULTS_DIR ...] [-o papers/common/results.tex]

Each RESULTS_DIR is a directory with the `summary.csv` that `bench/run.sh summarize` writes (after `bench/run.sh merge`
for a merged run), and optionally its `env.json`. Later directories override earlier ones, key by key, so a rerun of
one tool can be layered over a full run. The output is a list of

    \\defres{case/prime/tool/field}{value}

with `field` one of

    warm    median warm time, seconds            cold    cold time (launch to exit), seconds
    mem     peak resident memory                  status  ok, or the failure the harness recorded
    bars    number of bars the run reported       agree   a check mark, or a cross with the distance to the reference
    dist    distance to the reference barcode     ref     the reference tool's name for the case

and an `env/...` group (machine, date, commits) from `env.json`. The papers read these with `\\res`, `\\resT`,
`\\resC`, `\\resM` and `\\resA` (common/macros.tex). A cell with a failure prints the failure instead of a number
(`T/O`, `OOM`, `limit`, `--` for a tool that does not support the case), as a paper table would.

Nothing here invents a number: a field the harness left empty is not written, and the paper keeps its red placeholder.
"""
import argparse
import csv
import json
import sys
from pathlib import Path

FAILURES = {"timeout": "T/O", "oom": "OOM", "limit": "limit", "unsupported": "--", "missing": "--"}


def tex_escape(s):
    out = []
    for ch in str(s):
        out.append({"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#", "$": r"\$",
                    "{": r"\{", "}": r"\}", "~": r"\~{}", "^": r"\^{}"}.get(ch, ch))
    return "".join(out)


def seconds(x):
    v = float(x)
    if v >= 100:
        return f"{v:.0f}"
    if v >= 10:
        return f"{v:.1f}"
    if v >= 1:
        return f"{v:.2f}"
    return f"{v:.3f}"


def memory(mb):
    v = float(mb)
    return f"{v / 1024:.1f}\\,GB" if v >= 1024 else f"{v:.0f}\\,MB"


def failure(status):
    if status in FAILURES:
        return FAILURES[status]
    if status.startswith("error"):
        return "err"
    return "?"


def rows_of(directory):
    with open(Path(directory) / "summary.csv", newline="") as f:
        yield from csv.DictReader(f)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("results", nargs="+", help="results directories holding summary.csv")
    ap.add_argument("-o", "--out", default=str(Path(__file__).resolve().parent.parent / "common" / "results.tex"))
    args = ap.parse_args(argv)

    values = {}
    for directory in args.results:
        for r in rows_of(directory):
            key = f"{r['case']}/{r['p']}/{r['tool']}"
            status = r.get("status", "")
            ok = status == "ok"
            values[f"{key}/status"] = status
            if ok:
                if r.get("warm_median_s"):
                    values[f"{key}/warm"] = seconds(r["warm_median_s"])
                if r.get("cold_s"):
                    values[f"{key}/cold"] = seconds(r["cold_s"])
                if r.get("maxrss_mb") and float(r["maxrss_mb"]) > 0:
                    values[f"{key}/mem"] = memory(r["maxrss_mb"])
                if r.get("bars"):
                    values[f"{key}/bars"] = r["bars"]
                if r.get("agrees") == "True":
                    values[f"{key}/agree"] = r"\checkmark"
                elif r.get("agrees") == "False":
                    values[f"{key}/agree"] = r"$\times$ (" + tex_escape(r.get("vs_reference", "")) + ")"
                if r.get("vs_reference"):
                    values[f"{key}/dist"] = tex_escape(r["vs_reference"])
            else:
                for field in ("warm", "cold", "mem", "agree"):
                    values[f"{key}/{field}"] = failure(status)
        env_file = Path(directory) / "env.json"
        if env_file.exists():
            env = json.loads(env_file.read_text())
            for k in ("date", "host", "platform", "cpu", "cores", "mem_total", "tda4j_git", "tda4j_dirty", "node"):
                if env.get(k) not in (None, ""):
                    values[f"env/{k}"] = tex_escape(str(env[k]).splitlines()[0])

    with open(args.out, "w") as f:
        f.write("% Generated by papers/tools/bench-to-tex.py from: " + ", ".join(args.results) + "\n")
        f.write("% Do not edit by hand. A key that is missing here leaves a red placeholder in the PDF.\n")
        for k in sorted(values):
            f.write(f"\\defres{{{k}}}{{{values[k]}}}\n")
    print(f"{len(values)} values written to {args.out}")


if __name__ == "__main__":
    main(sys.argv[1:])
